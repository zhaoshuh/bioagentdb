"""生成论文 Table 1（疾病与检索面）与 Table 2（schema）→ docs/paper/final/tables.md。

用法: python scripts/make_tables.py [--stats PATH] [--db PATH] [--out PATH]
默认: v1.5 stats + _v15 快照。
"""

from __future__ import annotations

import argparse
import json
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.harvest.themes import THEME_SEEDS  # noqa: E402

DEFAULT_STATS = ROOT / "docs" / "versions" / "v1.5-stats" / "resource-stats.json"
DEFAULT_DB = ROOT / "data" / "releases" / "_v15" / "bioagentdb.sqlite3"
DEFAULT_OUT = None  # 必须显式 --out（避免无参运行静默覆盖 tables.md）
REQUIRE_OUT = True

SCHEMA_TABLES = {
    "papers": ["id", "pmid", "doi", "title", "journal", "year", "abstract", "da_text",
               "fulltext_source", "mined_status", "has_db_xref", "has_suppl"],
    "paper_themes": ["paper_id", "theme", "source"],
    "themes": ["slug", "name", "priority", "facets", "target_records"],
    "datasets": ["id", "fingerprint", "title", "description", "modality", "modalities",
                 "organism", "tissue", "disease", "platform", "sample_count", "status",
                 "confidence"],
    "dataset_links": ["dataset_id", "repository", "accession", "url", "link_type",
                      "is_primary", "reachable", "file_name"],
    "dataset_papers": ["dataset_id", "paper_id", "role"],
    "evidence": ["dataset_id", "paper_id", "zone", "quote"],
    "paper_audits": ["paper_id", "theme", "findings", "verdict", "records"],
}

PROTEIN = {
    "alzheimers-disease": "amyloid-β / tau", "als": "TDP-43 / SOD1",
    "parkinsons-disease": "α-synuclein", "frontotemporal-dementia": "tau / TDP-43",
    "huntingtons-disease": "huntingtin (polyQ)", "prion-disease": "PrP",
    "progressive-supranuclear-palsy": "tau", "dementia-with-lewy-bodies": "α-synuclein",
    "multiple-system-atrophy": "α-synuclein", "spinocerebellar-ataxia": "ataxin (polyglutamine, polyQ)",
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stats", default=str(DEFAULT_STATS))
    ap.add_argument("--db", default=str(DEFAULT_DB))
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    if REQUIRE_OUT:
        import sys as _sys
        if not any(a == "--out" or a.startswith("--out=") for a in _sys.argv):
            raise SystemExit("make_tables.py 需要显式 --out <path>")
    args = ap.parse_args()

    stats_path = Path(args.stats)
    db_path = Path(args.db)
    out_path = Path(args.out)
    stats = json.loads(stats_path.read_text(encoding="utf-8")) if stats_path.exists() else {}
    counts = {r["slug"]: r for r in stats.get("per_theme", [])}
    seeds = {s["slug"]: s for s in THEME_SEEDS}

    db = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True) if db_path.exists() else None
    extra = []
    if db:
        for r in db.execute("SELECT slug, name, priority FROM themes ORDER BY priority"):
            if r[0] not in seeds:
                extra.append((r[0], r[1], r[2]))
        db.close()

    version_label = stats_path.parent.name.replace("v", "v").replace("-stats", "")
    lines = ["# Paper tables", "",
             f"> Generated by `scripts/make_tables.py` · source: {db_path.parent.name} database + "
             f"`app/harvest/themes.py` · numbers from `{stats_path.as_posix()}` "
             f"(**v{version_label.replace('v', '')}**, October 2026).", "",
             "## Table 1 · Disease themes and query facets", "",
             "| priority | slug | protein | papers w/ data | datasets | base queries |",
             "|---|---|---|---|---|---|"]
    order = sorted(seeds.values(), key=lambda s: s["priority"])
    for s in order:
        c = counts.get(s["slug"], {})
        q = "; ".join((s.get("facets") or {}).get("base_queries", [])[:3])
        if len((s.get("facets") or {}).get("base_queries", [])) > 3:
            q += " …"
        lines.append(f"| {s['priority']} | {s['slug']} | {PROTEIN.get(s['slug'], '—')} | "
                     f"{c.get('papers_with_data', 0)} | {c.get('datasets', 0)} | `{q}` |")
    for slug, name, pr in extra:
        c = counts.get(slug, {})
        lines.append(f"| {pr} | {slug} | (on-demand) | {c.get('papers_with_data', 0)} | "
                     f"{c.get('datasets', 0)} | LLM-generated |")

    lines += ["", "## Table 2 · Record schema (key tables, subset)", "",
              "| table | fields |", "|---|---|"]
    for t, cols in SCHEMA_TABLES.items():
        lines.append(f"| `{t}` | {', '.join('`'+c+'`' for c in cols)} |")
    lines += ["", "_Paper-level record = papers + paper_themes; dataset-level record = "
              "datasets + dataset_links + evidence + dataset_papers._"]

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out_path}")
    print("\n".join(lines[:8]))


if __name__ == "__main__":
    main()
