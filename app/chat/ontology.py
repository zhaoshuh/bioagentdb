"""Online ontology lookup for profile concepts (OLS4 / MeSH / NCBI), with cache.

Synonyms are taken from ontology records, never generated by the LLM. If a
lookup fails, the profile simply has no ontology block; nothing is invented.
"""
from __future__ import annotations

import hashlib
import json
import logging
import re
from pathlib import Path

from app.core import utils
from app.core.config import cfg

logger = logging.getLogger(__name__)

_OLS = "https://www.ebi.ac.uk/ols4/api/search"
_ONTOLOGIES = {
    "disease": ["mondo", "efo"],
    "modality": ["edam"],
    "tissue": ["uberon"],
    "organism": ["ncbitaxon"],
    "topic": ["envo", "mondo"],
}
_CACHE_TTL_DAYS = 30


def _cache_path(kind: str, label: str) -> Path:
    digest = hashlib.sha1(f"{kind}|{label.casefold()}".encode("utf-8")).hexdigest()[:16]
    folder = cfg.cache_dir / "ontology"
    folder.mkdir(parents=True, exist_ok=True)
    return folder / f"{kind}-{digest}.json"


def _read_cache(path: Path) -> dict | None:
    try:
        if not path.exists():
            return None
        data = json.loads(path.read_text(encoding="utf-8"))
        return data.get("payload")
    except Exception:  # noqa: BLE001
        return None


def _write_cache(path: Path, payload: dict) -> None:
    try:
        path.write_text(json.dumps({"payload": payload}, ensure_ascii=False), encoding="utf-8")
    except Exception:  # noqa: BLE001
        pass


def _clean_label(text: str) -> str:
    return re.sub(r"\s+", " ", str(text or "")).strip()


def _score(label: str, doc: dict) -> int:
    """Only accept exact labels or exact ontology synonyms; never fuzzy-guess."""
    q = _clean_label(label).casefold()
    lab = _clean_label(doc.get("label")).casefold()
    if q and q == lab:
        return 100
    syns = []
    for key in ("exact_synonyms", "narrow_synonyms", "related_synonyms"):
        for s in doc.get(key) or []:
            syns.append(_clean_label(s).casefold())
    if q and q in syns:
        return 90
    if len(q) >= 4 and (q in lab or lab in q):
        return 40
    return 0


def _collect(doc: dict, ontology: str) -> dict:
    syns: list[str] = []
    for key in ("exact_synonyms", "narrow_synonyms", "related_synonyms"):
        for s in doc.get(key) or []:
            s = _clean_label(s)
            if s and s.casefold() != _clean_label(doc.get("label")).casefold():
                syns.append(s)
    # dedupe, keep order, cap
    out: list[str] = []
    seen: set[str] = set()
    for s in syns:
        k = s.casefold()
        if k not in seen:
            seen.add(k)
            out.append(s)
    return {
        "label": _clean_label(doc.get("label")),
        "id": str(doc.get("obo_id") or doc.get("short_form") or ""),
        "ontology": ontology,
        "synonyms": out[:12],
        "source": "OLS4",
    }


def lookup(label: str, kind: str = "topic") -> dict | None:
    """Look up a concept label in the relevant ontology. Returns None if absent."""
    label = _clean_label(label)
    if not label:
        return None
    kind = kind if kind in _ONTOLOGIES else "topic"
    path = _cache_path(kind, label)
    cached = _read_cache(path)
    if cached:
        return cached
    best_doc, best_ontology, best_score = None, "", 0
    for ontology in _ONTOLOGIES[kind]:
        try:
            data = utils.get_json(_OLS, params={
                "q": label, "ontology": ontology, "rows": 10, "exact": "false"},
                retries=0, timeout=8)
        except Exception as exc:  # noqa: BLE001
            logger.debug("ontology lookup failed (%s/%s): %s", kind, ontology, exc)
            continue
        docs = ((data or {}).get("response") or {}).get("docs") or []
        for doc in docs:
            score = _score(label, doc)
            if score > best_score:
                best_doc, best_ontology, best_score = doc, ontology, score
        if best_score >= 90:
            break
    if best_doc is None or best_score < 40:
        return None
    payload = _collect(best_doc, best_ontology)
    if payload.get("label"):
        _write_cache(path, payload)
        return payload
    return None


def enrich_profile(profile: dict) -> dict:
    """Attach ontology synonyms/IDs for core fields and a free-form concept tree.

    The LLM supplies labels/types; this function supplies the verified synonyms.
    """
    out = dict(profile)
    ontology: dict[str, dict] = dict(out.get("ontology") or {})
    targets: list[tuple[str, str]] = []
    topic = _clean_label(out.get("topic") or out.get("disease") or "")
    if topic:
        targets.append(("disease", topic))
    organism = _clean_label(out.get("organism") or "")
    if organism and organism.lower() not in ("any", "unknown"):
        targets.append(("organism", organism))
    tissue = _clean_label(out.get("tissue") or "")
    if tissue and tissue.lower() not in ("any", "unknown"):
        targets.append(("tissue", tissue))
    for m in (out.get("modalities") or [])[:3]:
        m = _clean_label(m)
        if m:
            targets.append(("modality", m))
    for c in (out.get("concepts") or [])[:8]:
        if isinstance(c, dict):
            label = _clean_label(c.get("label"))
            kind = str(c.get("type") or "topic").lower()
            if label and kind in _ONTOLOGIES:
                targets.append((kind, label))
    seen: set[tuple[str, str]] = set()
    for kind, label in targets:
        key = (kind, label.casefold())
        if key in seen:
            continue
        seen.add(key)
        info = lookup(label, kind)
        if info:
            ontology[f"{kind}:{label}"] = info
    if ontology:
        out["ontology"] = ontology
    return out
